public enum LightType
{
    Point,
    Spot,
    Ambient,
    Directional,
    Frustum,

}

public class ItemLightConverter
{

    /// <summary>
    /// Convert Light User Model to actual Gbx lights with more parameters.
    /// Note that generated parameters might not be the exact same as generated by tm.
    /// </summary>
    public void ConvertLightUserModels(CPlugSolid2Model model)
    {
        List<CPlugSolid2Model.Light> lights = [];

        var socket = GbxItemUtils.ParseSockets(model.Skel!)?.FirstOrDefault();
        foreach (var customLight in model.LightUserModels ?? [])
        {
            if(socket == null)
                throw new Exception("No socket found for light user model conversion.");
            var light = ConvertLight(customLight, socket);
            lights.Add(light);
        }
        model.LightUserModels = [];
        model.Lights = lights.ToArray();
    }

    public void ConvertLightUserModels(CGameItemModel item)
    {
        if (item.EntityModel is CGameCommonItemEntityModel common)
            ConvertLightUserModels(common.StaticObject!.Mesh!);
        else if(item.EntityModel is CPlugPrefab prefab)
        {
            foreach(var staticObject in ItemExtensions.Traverse<CPlugStaticObjectModel>(prefab))
            {
                ConvertLightUserModels(staticObject.Mesh!);
            }
            foreach (var dynaObject in ItemExtensions.Traverse<CPlugDynaObjectModel>(prefab))
            {
                ConvertLightUserModels(dynaObject.Mesh!);
            }
        }
    }

    CPlugSolid2Model.Light ConvertLight(CPlugLightUserModel lightUserModel, CPlugSkel.Socket socket)
    {
        var desiredLightType = GbxItemUtils.GetLightTypeFromLightUserModel(lightUserModel);
        var light = ItemLightHelper.CreateEmptyLight(desiredLightType);
        ItemLightHelper.LightUserModelToLightProperties(lightUserModel, socket, light, desiredLightType);
        return light;
    }

    

}
public static class ItemLightHelper
{
    public static void LightUserModelToLightProperties(CPlugLightUserModel lightUserModel, CPlugSkel.Socket socket, CPlugSolid2Model.Light light, LightType lightType)
    {
        var transform = socket.U02;
        light.U05 = transform;

        var cPlugLight = light.U03;
        cPlugLight.NightOnly = lightUserModel.NightOnly;
        cPlugLight.GetChunk<CPlugLight.Chunk0901D004>().U04 = lightUserModel.NightOnly ? 1 : 0;

        var gxLight = cPlugLight.Light;
        gxLight.Color = lightUserModel.Color;
        gxLight.Intensity = lightUserModel.Intensity;


        if (gxLight is GxLightPoint lp)
            FillLightPointFromLightUserModel(lightUserModel, lp);

        if (gxLight is GxLightBall lb)
            FillLightBallFromLightUserModel(lightUserModel, lb);

        if (gxLight is GxLightSpot ls)
            FillLightSpotFromLightUserModel(lightUserModel, ls);


    }

    public static void FillLightBallFromLightUserModel(CPlugLightUserModel lightUserModel, GxLightBall lightBall)
    {
        lightBall.Radius = lightUserModel.Distance;
        lightBall.RadiusSpecular = lightUserModel.Distance;
        lightBall.RadiusShadow = lightUserModel.Distance;
        lightBall.RadiusShadow = lightUserModel.Distance;
        lightBall.RadiusFlare = lightUserModel.Distance * 4;
        lightBall.EmittingRadius = lightUserModel.PointEmissionRadius;
        lightBall.EmittingCylinderLenZ = lightUserModel.PointEmissionLength;
        lightBall.GetChunk<GxLightBall.Chunk04002009>()!.U01 = lightUserModel.Distance;
    }
    public static void FillLightSpotFromLightUserModel(CPlugLightUserModel lightUserModel, GxLightSpot lightSpot)
    {
        lightSpot.AngleInner = lightUserModel.SpotInnerAngle;
        lightSpot.AngleOuter = lightUserModel.SpotOuterAngle;
        lightSpot.EmittingRadius = lightUserModel.SpotEmissionSizeX;
        lightSpot.EmittingCylinderLenZ = lightUserModel.SpotEmissionSizeY;
    }
    public static void FillLightPointFromLightUserModel(CPlugLightUserModel lightUserModel, GxLightPoint lightPoint)
    {
        lightPoint.FlareSize = 5;
    }

    public static CPlugSolid2Model.Light CreateEmptyLight(LightType lightType)
    {
        var light = new CPlugSolid2Model.Light();

        light.U01 = "";
        light.U02 = true;
        light.U06 = 1;
        light.U07 = 1;

        light.U09 = -990076000;
        light.U10 = 664;
        light.U11 = -990076632;

        light.U03 = CreateEmptyCPlugLight(lightType);
        return light;
    }

    public static CPlugLight CreateEmptyCPlugLight(LightType lightType)
    {
        var cplugLight = new CPlugLight();
        var c002 = cplugLight.CreateChunk<CPlugLight.Chunk0901D002>();
        var c003 = cplugLight.CreateChunk<CPlugLight.Chunk0901D003>();
        c003.Version = 1;
        var c004 = cplugLight.CreateChunk<CPlugLight.Chunk0901D004>();
        c004.Version = 0;
        c004.U01 = -1;
        c004.U02 = -1;
        c004.U03 = -1;
        c004.U04 = 0;
        c004.U05 = -1;

        cplugLight.AnimTimerName = "";
        cplugLight.AnimPeriodMin = 1;
        cplugLight.AnimPeriodMax = 1;
        cplugLight.NightOnly = false;
        cplugLight.ReflectByGround = false;
        cplugLight.SceneLightOnlyWhenTreeVisible = false;

        cplugLight.Light = CreateGxLight(lightType);
        return cplugLight;
    }

    public static GxLight CreateGxLight(LightType lightType)
    {
        GxLight light;
        switch (lightType)
        {
            case LightType.Point:
                {
                    var point = new GxLightBall();
                    var c1 = point.CreateChunk<GxLightPoint.Chunk04003004>();
                    var c2 = point.CreateChunk<GxLightBall.Chunk04002008>();
                    var c3 = point.CreateChunk<GxLightBall.Chunk04002009>();
                    var c4 = point.CreateChunk<GxLightBall.Chunk0400200A>();
                    c4.U01 = 0.015625f;

                    light = point;
                    point.FlareSize = 0;
                    point.FlareBiasZ = 0;
                }
                break;
            case LightType.Spot:
                {
                    var spot = new GxLightSpot();

                    var c1 = spot.CreateChunk<GxLightSpot.Chunk0400B003>();
                    c1.U01 = 1; // sub-light count X?
                    c1.U02 = 1; // sub-light count Y?
                    c1.U03 = 0;
                    c1.Version = 1;

                    light = spot;
                    spot.AngleInner = 0;
                    spot.AngleOuter = 45;
                    spot.AngleFlare = 20;
                    spot.FalloffExponent = 0;
                    spot.AngleInnerShadow = 0;
                    spot.AngleOuterShadow = 20;
                }
                break;
            case LightType.Ambient:
                {
                    var ambient = new GxLightAmbient();
                    light = ambient;

                    var c1 = ambient.CreateChunk<GxLightAmbient.Chunk04005000>();
                    ambient.ShadeMinY = 0; //Probably a hemisphere - style ambient
                    ambient.ShadeMaxY = 0;
                }
                break;
            case LightType.Directional:
                {
                    
                    var dir = new GxLightDirectional();
                    light = dir;

                    var c1 = dir.CreateChunk<GxLightDirectional.Chunk04007001>();
                    var c2 = dir.CreateChunk<GxLightDirectional.Chunk04007002>();
                    var c3 = dir.CreateChunk<GxLightDirectional.Chunk04007003>();
                    var c4 = dir.CreateChunk<GxLightDirectional.Chunk04007004>();
                    var c5 = dir.CreateChunk<GxLightDirectional.Chunk04007005>();

                    dir.UseBoundaryHint = false;
                    dir.BoundaryHintPos = new Vec3(0, 0, 0);//Likely a hint for the region the light matters in, used to fit shadow maps or cull. The position would be the center of that region.
                    dir.DazzleAngleMax = 0; // A glare effect when the camera looks toward the light.
                    dir.DazzleIntensity = 0;
                    dir.DblSidedRGB = Color.White.ToVec3(); // Probably the color applied to back faces of double-sided or translucent geometry, such as foliage or thin cloth.
                    dir.ReverseRGB = Color.White.ToVec3(); // A fake fill or bounce light coming from the opposite direction of the main light, with its own color and intensity. This is a common trick to avoid fully black shadowed sides.
                    dir.ReverseIntens = 0;
                    dir.EmittAngularSize = 0; // The angular size of the light source as seen from the surface (like the sun's disc). It probably controls soft-shadow penumbra width.
                    dir.FlareAngularSize = 0; // The angular size of the lens flare or sun disc visual, as opposed to the physical emitter size used for shadows.
                }
                break;
            case LightType.Frustum:
                {
                    var frustum = new GxLightFrustum();
                    light = frustum;

                    var c1 = frustum.CreateChunk<GxLightFrustum.Chunk0400A004>();
                    c1.U01 = 0;
                    c1.U02 = 0;
                    c1.U03 = 0;
                    c1.U04 = 0;
                    c1.U05 = 0;
                    c1.U06 = 0;
                    c1.U07 = 0;
                    c1.U08 = 0;

                    var c2 = frustum.CreateChunk<GxLightFrustum.Chunk0400A006>();
                    c2.U01 = false;
                    c2.U02 = new BoxAligned();
                    c2.U03 = 0;
                }
                break;

            default:
                throw new NotImplementedException("Light type not supported");
        }
        if (light.TryCreateChunk<GxLight.Chunk04001009>(out var cl1))
        {
            // noop
        }
        if (light.TryCreateChunk<GxLight.Chunk04001008>(out var cl2))
        {
            // noop
        }
        if (light.TryCreateChunk<GxLight.Chunk0400100A>(out var cl3))
        {
            // noop
        }

        light.DoLighting = true;
        light.LightMapOnly = false;
        light.IsShadowGen = true;
        light.DoSpecular = true;
        light.HasLensFlare = false;
        light.HasSprite = false;
        light.EnableGroup0 = true;
        light.EnableGroup1 = false;
        light.EnableGroup2 = false;
        light.EnableGroup3 = false;
        light.Color = Color.White.ToVec3();
        light.Intensity = 1;
        light.ShadowIntensity = 1;
        light.FlareIntensity = 1;
        light.ShadowRGB = Color.White.ToVec3();
        light.DiffuseIntensity = 1f;
        light.SpecularIntens = 1;
        light.SpecularPower = 1;

        if (light is GxLightBall lb)
        {

            if (lb.TryCreateChunk<GxLightBall.Chunk04002008>(out var c1))
            {
                // Initialize chunk c1 if needed
            }
            if (lb.TryCreateChunk<GxLightBall.Chunk04002009>(out var c2))
            {
                c2.U01 = 100f;// radius??
            }
            if (lb.TryCreateChunk<GxLightBall.Chunk0400200A>(out var c3))
            {
                c3.U01 = 0.015625f;// ? (1/64) / resolution? | epsilo? | grid?
            }
            lb.Radius = 0;
            lb.Attenuation1 = 0;
            lb.Attenuation2 = 0;
            lb.EmittingRadius = 0;
            lb.AmbientRGB = Color.Black.ToVec3();
            lb.Flags = 16;
            lb.RadiusSpecular = 0;
            lb.RadiusShadow = 0;
            lb.RadiusFlare = 0;
            lb.EmittingCylinderLenZ = 0;
            lb.AttHTnLR = 10;
            lb.AttHTnLR2 = 0;
            lb.AttHyper2DerivAt0 = -1.5f;
            lb.AttHyper2Tension = 0.3f;
        }
        if (light is GxLightPoint lp)
        {
            if (lp.TryCreateChunk<GxLightPoint.Chunk04003004>(out var c1))
            {
                // Initialize chunk c1 if needed
            }
            lp.FlareSize = 0;
            lp.FlareBiasZ = 0;
        }
        if (light is GxLightNotAmbient na)
        {
            // noop
        }
        if(light is GxLightSpot ls)
        {
            ls.LightMapOnly = true;
            ls.DoSpecular = false;
            ls.SpecularIntens = 0;
            ls.SpecularPower = 0;
        }


        return light;
    }


}
